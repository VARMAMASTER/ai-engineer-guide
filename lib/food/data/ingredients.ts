function expand(seed: IngredientSeed): Ingredient {
  const { n } = seed
  return {
    id: seed.id,
    name: seed.name,
    aliases: seed.aliases,
    group: seed.group,
    state: seed.state,
    prominence: seed.prominence ?? 0,
    per100g: {
      kcal: n.kcal,
      protein_g: n.protein_g,
      carb_g: n.carb_g,
      fat_g: n.fat_g,
      // `?? null` and NOT `?? 0`. This single line is where the zero/unknown
      // distinction is actually created: an omitted key in the seed above
      // means nobody measured it.
      sugar_g: n.sugar_g ?? null,
      sat_fat_g: n.sat_fat_g ?? null,
      fibre_g: n.fibre_g ?? null,
      sodium_mg: n.sodium_mg ?? null,
      calcium_mg: n.calcium_mg ?? null,
      iron_mg: n.iron_mg ?? null,
      potassium_mg: n.potassium_mg ?? null,
      vitamin_c_mg: n.vitamin_c_mg ?? null,
    },
    servings: seed.servings.map(([label, grams]) => ({ label, grams })),
    source: seed.source,
    confidence: seed.confidence,
    sourceNote: seed.note,
  }
}

export const INGREDIENTS: readonly Ingredient[] = SEED.map(expand)
