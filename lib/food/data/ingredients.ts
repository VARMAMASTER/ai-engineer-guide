/**
 * The ingredient reference set: common Indian kitchen ingredients, per 100 g.
 *
 * ---------------------------------------------------------------------------
 * WHY THIS FILE IS THE SOURCE OF TRUTH AND NOT A SQL SEED
 *
 * These numbers are the most review-sensitive content in the app — a wrong
 * digit here propagates into every dish that uses the ingredient — so they
 * live in git where a diff is readable, they are type-checked, and
 * `tests/unit/food/reference.test.ts` holds them to invariants (macros add up
 * to roughly the stated energy, ids are unique and stable, every recipe's
 * ingredients resolve). `scripts/seed-food.ts` pushes this file into Postgres,
 * which is the SEARCH INDEX and the growth path, not the authority.
 *
 * It also means `/food/[id]` prerenders and works offline and with JavaScript
 * off, which a database read on every page view would not.
 *
 * ---------------------------------------------------------------------------
 * WHERE THE NUMBERS COME FROM, AND WHERE THEY DO NOT
 *
 * `source` and `confidence` are on every row and they are not decoration:
 *
 *   ifct-2017  The Indian Food Composition Tables (ICMR-NIN). Used for foods
 *              where the Indian figure is the one that matters and is the
 *              commonly cited one — paneer, ragi, jaggery, Indian fish.
 *   usda-fdc   USDA FoodData Central. Used for foods that are compositionally
 *              the same everywhere: pulses, grains, vegetables, fruit, oils,
 *              nuts, meat, egg. This is where most of the high-confidence
 *              rows come from, and saying so is more honest than stamping
 *              them all "IFCT" because the app is Indian.
 *   estimate   A considered figure. Never 'high' confidence — the database
 *              refuses that combination.
 *
 * Micronutrients are mostly NULL, on purpose. They are the least reliable and
 * most laborious part of any food table, and an absent value renders as "not
 * known" rather than 0. Filling them with plausible numbers would be the
 * single most damaging thing this file could do.
 * ---------------------------------------------------------------------------
 */

